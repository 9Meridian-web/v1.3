import { GeminiService } from "./geminiService";

import { JsonParserService } from "../parsers/jsonParserService";

/*
|--------------------------------------------------------------------------
| Base AI Service
|--------------------------------------------------------------------------
*/

export abstract class BaseAIService<

    Request,

    AIResponse,

    Result = AIResponse

> {

    /*
    |--------------------------------------------------------------------------
    | Public Handler
    |--------------------------------------------------------------------------
    */

    async handle(

        request: Request

    ): Promise<Result> {

        /*
        |--------------------------------------------------------------------------
        | Prompt
        |--------------------------------------------------------------------------
        */

        const prompt =

            this.buildPrompt(

                request

            );

        /*
        |--------------------------------------------------------------------------
        | Gemini
        |--------------------------------------------------------------------------
        */

        const response =

            await GeminiService.generate({

                prompt,

                temperature:

                    this.temperature()

            });

        /*
        |--------------------------------------------------------------------------
        | Parse
        |--------------------------------------------------------------------------
        */

        const parsed =

            JsonParserService.parse<AIResponse>(

                response

            );

        /*
        |--------------------------------------------------------------------------
        | Validate
        |--------------------------------------------------------------------------
        */

        const validated =

            this.validate(

                parsed

            );

        /*
        |--------------------------------------------------------------------------
        | Execute
        |--------------------------------------------------------------------------
        */

        return await this.execute(

            validated,

            request

        );

    }

    /*
    |--------------------------------------------------------------------------
    | Temperature
    |--------------------------------------------------------------------------
    */

    protected temperature(): number {

        return 0.1;

    }

    /*
    |--------------------------------------------------------------------------
    | Build Prompt
    |--------------------------------------------------------------------------
    */

    protected abstract buildPrompt(

        request: Request

    ): string;

    /*
    |--------------------------------------------------------------------------
    | Validate AI Output
    |--------------------------------------------------------------------------
    */

    protected abstract validate(

        data: AIResponse

    ): AIResponse;

    /*
    |--------------------------------------------------------------------------
    | Execute
    |--------------------------------------------------------------------------
    */

    protected async execute(

        data: AIResponse,

        _request: Request

    ): Promise<Result> {

        return data as unknown as Result;

    }

}